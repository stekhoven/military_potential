export function errorMessage(lang, error) {
  const code =
    typeof error === "string" ? error : error?.code || error?.error || "";
  const key =
    code === "INVALID_UNICODE"
      ? "invalidUnicode"
      : code === "CSRF_FAILED"
        ? "csrfFailed"
        : code === "LOGIN_THROTTLED"
          ? "loginThrottled"
          : code === "AUTH_REQUIRED"
            ? "sessionExpired"
            : code === "LOGIN_FAILED"
              ? "authentication"
              : code.includes("CONFLICT") || code === "conflict"
                ? "conflict"
                : code.includes("FORBIDDEN") || code === "forbidden"
                  ? "forbidden"
                  : code.includes("AUTHENTICATION") ||
                      code === "invalid_credentials"
                    ? "authentication"
                    : code.includes("NORMALIZATION_ZERO")
                      ? "normalizationZero"
                      : code.includes("TARGET_UNREACHABLE")
                        ? "targetUnreachable"
                        : code.includes("SCENARIO_WEIGHTS_ZERO")
                          ? "weightsZero"
                          : code === "connection"
                            ? "connection"
                            : code === "unauthenticated"
                              ? "sessionExpired"
                              : "invalid";
  return translate(lang, key);
}
